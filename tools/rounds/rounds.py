def write_caliber(tag, mine):
    c = CALIBERS[tag]
    path = TWEAKS / c["file"]
    text = path.read_text()
    block = BEGIN + "\n\n" + "".join(round_yaml(tag, k) for k in mine) + END + "\n"
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END) + "\n", lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block
    # The caliber's lists: the hand-written entries, then the generated ones.
    owned = {ids(tag, k)["sel"] for k in mine} | {ids(tag, k)["ammo"] for k in mine}
    def lists(name, extra):
        m = re.search(rf'^AmmoOverhaul\.{c["key"]}\.{name}: \[(.*)\]$', text, flags=re.M)
        items = [s.strip() for s in m.group(1).split(",")]
        kept = []
        for s in items:
            if s.strip('"') not in owned:
                kept.append(s)
        return m, kept + extra
    sels = [f'"{ids(tag, k)["sel"]}"' for k in mine]
    ammos = [f'"{ids(tag, k)["ammo"]}"' for k in mine]
    m_s, all_s = lists("selectors", sels)
    m_a, all_a = lists("selectorAmmo", ammos)
    hand = len(all_s) - len(sels)
    m_t = re.search(rf'^AmmoOverhaul\.{c["key"]}\.selectorTiers: \[(.*)\]$', text, flags=re.M)
    tiers = [s.strip() for s in m_t.group(1).split(",")][:hand] + [str(k["tier"]) for k in mine]
    for m, items in ((m_s, all_s), (m_a, all_a), (m_t, tiers)):
        line = m.group(0)
        new = line[:line.index("[")] + "[" + ", ".join(items) + "]"
        text = text.replace(line, new)
    path.write_text(text)


def write_text(all_rounds):
    pairs = []
    seen = set()
    for tag, k in all_rounds:
        i = ids(tag, k)
        pairs.append((i["name"], title(tag, k)))
        if i["desc"] not in seen:
            seen.add(i["desc"])
            pairs.append((i["desc"], k["desc"]))
    lines = [f'    ArrayPush(t, "{key}"); ArrayPush(t, "{text}");'.replace("\n", "\\n") for key, text in pairs]
    reds = ("module AmmoOverhaul.Localization\n\n"
            "// Generated by tools/rounds/rounds.py (Rare and Epic rounds); edit there.\n"
            "public abstract class AORoundTexts {\n"
            "  // Key, text, key, text, ...\n"
            "  public static func Pairs() -> array<String> {\n"
            "    let t: array<String>;\n" + "\n".join(lines) + "\n    return t;\n  }\n}\n")
    (ROOT / "src" / "scripts" / "AmmoOverhaul" / "LocalizationRounds.reds").write_text(reds)


def write_art(all_rounds):
    # A caliber can have its own box colors (per_caliber look and look_key); otherwise the kind's.
    looks = {k.get("look_key", k["load"]): k["look"] for _, k in all_rounds}
    art = {}
    for tag, k in all_rounds:
        c = CALIBERS[tag]
        label = [c["label"], k["title"].upper()] if c["label"] else [k["title"].upper()]
        over = dict(k.get("art", {}))
        if c["shape"] in ("G12", "G4"):
            # Shells: a rolled crimp over one projectile (as the Slugs), a star crimp over pellets.
            over.setdefault("crimp", "roll" if "Fires one projectile" in k["desc"] else "star")
        art[ids(tag, k)["art"]] = dict(shape=c["shape"], over=over, look=k.get("look_key", k["load"]), label=label,
                                       tier=k.get("tier"), faction=k.get("faction"))
    (ROOT / "tools" / "render" / "rounds_tiers.json").write_text(
        json.dumps(dict(looks=looks, rounds=art), indent=1) + "\n")


def write_refs(all_rounds):
    refs = set()
    for tag, k in all_rounds:
        refs.add(CALIBERS[tag]["base_ammo"])
        refs.add(CALIBERS[tag]["base_sel"])
        refs.update(m[0] for m in k["stats"])
        refs.update("BaseStats." + m[3] for m in k["stats"] if len(m) > 3)
        refs.update(e for e, _ in k.get("hit", {}).get("effects", []))
        rank = k.get("hit", {}).get("rank", {})
        refs.update(rank[f] for f in ("effect", "tough", "player", "blast") if f in rank)
        if k.get("program"):
            refs.add(k["program"])
        if k.get("attack_package"):
            refs.add(k["attack_package"])
        refs.update(k.get("hit", {})[f] for f in ("npc_blast", "effect_blast") if f in k.get("hit", {}))
        if k.get("hit", {}).get("head_effect"):
            refs.add(k["hit"]["head_effect"])
    (ROOT / "tools" / "rounds" / "refs.txt").write_text("\n".join(sorted(refs)) + "\n")


def main():
    all_rounds = rounds()
    for tag in CALIBERS:
        write_caliber(tag, [k for t, k in all_rounds if t == tag])
    write_text(all_rounds)
    write_art(all_rounds)
    write_refs(all_rounds)
    print(f"{len(all_rounds)} rounds")


if __name__ == "__main__":
    main()

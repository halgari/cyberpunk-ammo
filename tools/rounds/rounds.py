# --- Stat modifiers ---------------------------------------------------------------------------


def mult(stat, value):
    return ("BaseStats." + stat, "Multiplier", value)


def add(stat, value):
    return ("BaseStats." + stat, "Additive", value)


def damage(f):
    return [mult("DamagePerHit", f)]


def armor(f):
    # The share of the target's armor ignored (negative: armor counts for more).
    return [add("CanWeaponIgnoreArmor", f)]


def recoil(f):
    return [mult("RecoilKickMin", f), mult("RecoilKickMax", f)]


SPREADS = ["SpreadDefaultX", "SpreadDefaultY", "SpreadMaxX", "SpreadMaxY",
           "SpreadAdsDefaultX", "SpreadAdsDefaultY", "SpreadAdsMaxX", "SpreadAdsMaxY",
           # The Tactician's spread has a floor: left alone it sits above a tightened Max.
           "SpreadMinX", "SpreadMinY", "SpreadAdsMinX", "SpreadAdsMinY"]


def spread(f):
    return [mult(s, f) for s in SPREADS]


def sway(f):
    return [mult("SwaySideMaximumAngleDistance", f), mult("SwayTraversalTime", 1 / f)]


def range_(f):
    return [mult("EffectiveRange", f)]


# One projectile carrying the shot's damage, as the Slugs: take away the gun's pellets, add one
# back (the NPC pellet ratio reads these two modifiers).
def one_projectile():
    return [("BaseStats.ProjectilesPerShot", "Additive", -1, "ProjectilesPerShotBase"),
            add("ProjectilesPerShot", 1)] + spread(0.2)


def projectiles(n):
    # Exactly n projectiles, whatever the gun fires (a player's Omaha fires 3, an NPC's 1): take away
    # the gun's own, add n, as one_projectile(). The engine splits the shot's damage across them.
    return [("BaseStats.ProjectilesPerShot", "Additive", -1, "ProjectilesPerShotBase"),
            add("ProjectilesPerShot", n)]



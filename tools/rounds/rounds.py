def fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        s = ("%.4f" % v).rstrip("0")
        return s + "0" if s.endswith(".") else s
    return str(v)


def rounds():
    """(caliber tag, kind with per-caliber overrides) for every round, in table order per caliber."""
    out = []
    for tag in CALIBERS:
        for kind in KINDS:
            if tag in kind["calibers"]:
                k = dict(kind)
                k.update(kind.get("per_caliber", {}).get(tag, {}))
                out.append((tag, k))
    return out


def ids(tag, k):
    c = CALIBERS[tag]
    load = k["load"]
    return dict(ammo=f"Ammo.AO_{c['ammo']}_{load}", sel=f"Items.AO_Feed_{c['sel']}_{load}",
                icon=f"AO_{c['loc']}_{load}", part=f"ao_{c['loc'].lower()}_{load.lower()}",
                art=f"{c['loc'].lower()}-{load.lower()}", name=f"AO-Ammo-{c['loc']}-{load}",
                desc=desc_key(tag, k))


def title(tag, k):
    return (CALIBERS[tag]["name"] + " " + k["title"]).strip()


def desc_key(tag, k):
    # Shared per kind, unless the caliber has its own text.
    own = "desc" in k.get("per_caliber", {}).get(tag, {})
    return f"AO-Ammo-{CALIBERS[tag]['loc']}-{k['load']}-Desc" if own else f"AO-Ammo-{k['load']}-Desc"


def modifier_yaml(stat, mtype, value, ref=None):
    if ref:
        # value times the gun's (refObject Root) `ref` stat.
        return (f"    - !append\n      $type: CombinedStatModifier\n      statType: {stat}\n"
                f"      modifierType: {mtype}\n      refStat: BaseStats.{ref}\n      refObject: Root\n"
                f"      opSymbol: '*'\n      value: {fmt(value)}\n")
    return (f"    - !append\n      $type: ConstantStatModifier\n      statType: {stat}\n"
            f"      modifierType: {mtype}\n      value: {fmt(value)}\n")


def price_yaml(tier):
    m = PRICE[tier]
    one = (f"    - !append\n      $type: ConstantStatModifier\n      statType: BaseStats.Price\n"
           f"      modifierType: Multiplier\n      value: {m}\n")
    return f"  buyPrice:\n{one}  sellPrice:\n{one}"


def round_yaml(tag, k):
    c, i, q = CALIBERS[tag], ids(tag, k), QUALITY[k["tier"]]
    y = f"# {title(tag, k)} ({q})\n"
    y += (f"{i['ammo']}:\n  $base: {c['base_ammo']}\n  quality: Quality.{q}\n"
          f"  # {q}: x{PRICE[k['tier']]} on the Uncommon's price, so x{2 * PRICE[k['tier']]} of the Common round's.\n"
          + price_yaml(k["tier"]) +
          f"  displayName: LocKey#{i['name']}\n  localizedDescription: LocKey#{i['desc']}\n"
          f"  iconPath: {i['icon']}\n"
          f"  tags: [Ammo, ShowStackPrice, AO_Ammo, AO_Tier_{k['tier']}, AO_Family_{c['family']}]\n\n")
    hit = k.get("hit", {})
    flats = []
    if hit.get("effects"):
        flats.append(("aoEffects", "[" + ", ".join(f'"{e}"' for e, _ in hit["effects"]) + "]"))
        flats.append(("aoEffectChances", "[" + ", ".join(fmt(float(ch)) for _, ch in hit["effects"]) + "]"))
    if hit.get("share"):
        flats.append(("aoShareType", f'"{hit["share"][0]}"'))
        flats.append(("aoShare", fmt(float(hit["share"][1]))))
    if hit.get("machine"):
        flats.append(("aoMachineBonus", fmt(float(hit["machine"]))))
    if hit.get("nonlethal"):
        flats.append(("aoNonlethal", "true"))
    for name, v in hit.get("roll", {}).items():
        flats.append((name, fmt(float(v))))
    for name, v in flats:
        y += f"{i['ammo']}.{name}: {v}\n"
    if flats:
        y += "\n"
    y += (f"UIIcon.{i['icon']}:\n  $type: UIIcon\n  atlasPartName: {i['part']}\n"
          f"  atlasResourcePath: ammooverhaul\\icons\\ao_ammo_icons.inkatlas\n\n")
    y += (f"{i['sel']}:\n  $base: {c['base_sel']}\n  displayName: LocKey#{i['name']}\n"
          f"  localizedDescription: LocKey#{i['desc']}\n  iconPath: {i['icon']}\n  quality: Quality.{q}\n")
    if k["stats"]:
        y += "  statModifiers:\n" + "".join(modifier_yaml(*m) for m in k["stats"])
    return y + "\n"


def write_caliber(tag, mine):
    c = CALIBERS[tag]
    path = TWEAKS / c["file"]
    text = path.read_text()
    block = BEGIN + "\n\n" + "".join(round_yaml(tag, k) for k in mine) + END + "\n"
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END) + "\n", lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block
    # The caliber's lists: the hand-written entries, then the generated ones.
    owned = {ids(tag, k)["sel"] for k in mine} | {ids(tag, k)["ammo"] for k in mine}
    def lists(name, extra):
        m = re.search(rf'^AmmoOverhaul\.{c["key"]}\.{name}: \[(.*)\]$', text, flags=re.M)
        items = [s.strip() for s in m.group(1).split(",")]
        kept = []
        for s in items:
            if s.strip('"') not in owned:
                kept.append(s)
        return m, kept + extra
    sels = [f'"{ids(tag, k)["sel"]}"' for k in mine]
    ammos = [f'"{ids(tag, k)["ammo"]}"' for k in mine]
    m_s, all_s = lists("selectors", sels)
    m_a, all_a = lists("selectorAmmo", ammos)
    hand = len(all_s) - len(sels)
    m_t = re.search(rf'^AmmoOverhaul\.{c["key"]}\.selectorTiers: \[(.*)\]$', text, flags=re.M)
    tiers = [s.strip() for s in m_t.group(1).split(",")][:hand] + [str(k["tier"]) for k in mine]
    for m, items in ((m_s, all_s), (m_a, all_a), (m_t, tiers)):
        line = m.group(0)
        new = line[:line.index("[")] + "[" + ", ".join(items) + "]"
        text = text.replace(line, new)
    path.write_text(text)


def write_text(all_rounds):
    pairs = []
    seen = set()
    for tag, k in all_rounds:
        i = ids(tag, k)
        pairs.append((i["name"], title(tag, k)))
        if i["desc"] not in seen:
            seen.add(i["desc"])
            pairs.append((i["desc"], k["desc"]))
    lines = [f'    ArrayPush(t, "{key}"); ArrayPush(t, "{text}");'.replace("\n", "\\n") for key, text in pairs]
    reds = ("module AmmoOverhaul.Localization\n\n"
            "// Generated by tools/rounds/rounds.py (Rare and Epic rounds); edit there.\n"
            "public abstract class AORoundTexts {\n"
            "  // Key, text, key, text, ...\n"
            "  public static func Pairs() -> array<String> {\n"
            "    let t: array<String>;\n" + "\n".join(lines) + "\n    return t;\n  }\n}\n")
    (ROOT / "src" / "scripts" / "AmmoOverhaul" / "LocalizationRounds.reds").write_text(reds)


def write_art(all_rounds):
    looks = {k["load"]: k["look"] for _, k in all_rounds}
    art = {}
    for tag, k in all_rounds:
        c = CALIBERS[tag]
        label = [c["label"], k["title"].upper()] if c["label"] else [k["title"].upper()]
        over = dict(k.get("art", {}))
        if c["shape"] in ("G12", "G4"):
            # Shells: a rolled crimp over one projectile (as the Slugs), a star crimp over pellets.
            over.setdefault("crimp", "roll" if "Fires one projectile" in k["desc"] else "star")
        art[ids(tag, k)["art"]] = dict(shape=c["shape"], over=over, look=k["load"], label=label)
    (ROOT / "tools" / "render" / "rounds_tiers.json").write_text(
        json.dumps(dict(looks=looks, rounds=art), indent=1) + "\n")


def write_refs(all_rounds):
    refs = set()
    for tag, k in all_rounds:
        refs.add(CALIBERS[tag]["base_ammo"])
        refs.add(CALIBERS[tag]["base_sel"])
        refs.update(m[0] for m in k["stats"])
        refs.update("BaseStats." + m[3] for m in k["stats"] if len(m) > 3)
        refs.update(e for e, _ in k.get("hit", {}).get("effects", []))
    (ROOT / "tools" / "rounds" / "refs.txt").write_text("\n".join(sorted(refs)) + "\n")


def main():
    all_rounds = rounds()
    for tag in CALIBERS:
        write_caliber(tag, [k for t, k in all_rounds if t == tag])
    write_text(all_rounds)
    write_art(all_rounds)
    write_refs(all_rounds)
    print(f"{len(all_rounds)} rounds")


if __name__ == "__main__":
    main()

def fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        s = ("%.4f" % v).rstrip("0")
        return s + "0" if s.endswith(".") else s
    return str(v)


def rounds():
    """(caliber tag, kind with per-caliber overrides) for every round, in table order per caliber."""
    out = []
    for tag in CALIBERS:
        for kind in KINDS:
            if tag in kind["calibers"]:
                k = dict(kind)
                k.update(kind.get("per_caliber", {}).get(tag, {}))
                out.append((tag, k))
    return out


def ids(tag, k):
    c = CALIBERS[tag]
    load = k["load"]
    # Hack rounds share one icon across the three calibers.
    hack = k.get("hack")
    return dict(ammo=f"Ammo.AO_{c['ammo']}_{load}", sel=f"Items.AO_Feed_{c['sel']}_{load}",
                icon=f"AO_{load}" if hack else f"AO_{c['loc']}_{load}",
                part=f"ao_{load.lower()}" if hack else f"ao_{c['loc'].lower()}_{load.lower()}",
                art=f"hack-{load.lower()}" if hack else f"{c['loc'].lower()}-{load.lower()}",
                name=f"AO-Ammo-{c['loc']}-{load}", desc=desc_key(tag, k))


def title(tag, k):
    name = (CALIBERS[tag]["name"] + " " + k["title"]).strip()
    if k.get("hack"):
        return f"{name} [Hack]"
    return f"{name} {FACTION_TAG[k['faction']]}" if k.get("faction") else name


def desc_key(tag, k):
    # Shared per kind, unless the caliber has its own text.
    own = "desc" in k.get("per_caliber", {}).get(tag, {})
    return f"AO-Ammo-{CALIBERS[tag]['loc']}-{k['load']}-Desc" if own else f"AO-Ammo-{k['load']}-Desc"


def modifier_yaml(stat, mtype, value, ref=None):
    if ref:
        # value times the gun's (refObject Root) `ref` stat.
        return (f"    - !append\n      $type: CombinedStatModifier\n      statType: {stat}\n"
                f"      modifierType: {mtype}\n      refStat: BaseStats.{ref}\n      refObject: Root\n"
                f"      opSymbol: '*'\n      value: {fmt(value)}\n")
    return (f"    - !append\n      $type: ConstantStatModifier\n      statType: {stat}\n"
            f"      modifierType: {mtype}\n      value: {fmt(value)}\n")


def price_yaml(tier, price=None):
    m = PRICE[tier] if price is None else price
    one = (f"    - !append\n      $type: ConstantStatModifier\n      statType: BaseStats.Price\n"
           f"      modifierType: Multiplier\n      value: {m}\n")
    return f"  buyPrice:\n{one}  sellPrice:\n{one}"



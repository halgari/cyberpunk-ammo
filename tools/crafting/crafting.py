#!/usr/bin/env python3
"""Crafting and disassembly records for every round (spec
docs/superpowers/specs/2026-10-29-ammo-crafting-design.md).

Reads each caliber file's flats (family, selectorAmmo, selectorTiers, craftBatch) and writes, at the
end of that file, a generated block with:
  - Crafting.AO_Cost_<family>_<tier>: the batch cost (Tech 1, Power 2, Smart 4 of the tier's
    components), set as each round's craftingData (in zz_crafting_costs.yaml);
  - Items.AO_Recipe_<round>: an ItemRecipe making the tier's batch of the round. Uncommon and up
    are the recipe items handed out in loot and gun shops: picking one up teaches the recipe
    (vanilla's CraftingSystemInventoryCallback). Common ones only feed GetAmmoBulletAmount;
  - <ammo>.aoRecipe, <ammo>.aoScrapRounds, <ammo>.aoScrapGive: read by Crafting.reds.
The 4 vanilla ammo records keep their vanilla cost and recipe; they get only the flats. Legendary
rounds (tier 4) are never crafted: no cost, no recipe, only the disassembly flats.
Also writes src/scripts/AmmoOverhaul/LocalizationRecipes.reds (recipe item names).
Run after tools/rounds/rounds.py, which rewrites the caliber lists this reads.
"""
import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
TWEAKS = ROOT / "src" / "tweaks" / "AmmoOverhaul"
SCRIPTS = ROOT / "src" / "scripts" / "AmmoOverhaul"
BEGIN = "# === GENERATED by tools/crafting/crafting.py: crafting. Edit there. ==="
END = "# === END GENERATED CRAFTING ==="
COSTS = "zz_crafting_costs.yaml"

COST = {"Tech": 1, "Power": 2, "Smart": 4}
MATERIAL = ["Items.CommonMaterial1", "Items.UncommonMaterial1", "Items.RareMaterial1", "Items.EpicMaterial1"]
QUALITY = ["Common", "Uncommon", "Rare", "Epic"]
LEGENDARY = 4
DIVISOR = [1, 2, 3, 4]
# A round's price over its caliber's Common round: x2 per tier (CATALOG, tiers.lua).
TIER_PRICE = [1, 2, 4, 8]
VANILLA = {"Ammo.HandgunAmmo": "Ammo.RecipeHandgunAmmo", "Ammo.RifleAmmo": "Ammo.RecipeRifleAmmo",
           "Ammo.ShotgunAmmo": "Ammo.RecipeShotgunAmmo", "Ammo.SniperRifleAmmo": "Ammo.RecipeSniperRifleAmmo"}
# Each caliber's Common round price, as the multiplier on Price.Ammo (read in game 2026-10-29: the
# Common round's buyPrice Multipliers). crafting.lua checks the recipe prices this gives.
COMMON_PRICE = {"Power_9mm": 1.0, "Power_45": 1.2, "Power_12mm": 1.6, "Power_556": 1.0,
                "Power_762": 1.3, "Power_127": 2.0, "Power_12ga": 1.0, "Power_4ga": 2.0,
                "Tech_Light": 1.0, "Tech_Heavy": 1.5, "Smart_10": 1.0, "Smart_20": 1.3, "Smart_25": 2.5}


def tier_batch(common, tier):
    """Rounds per crafted batch: the Common batch over 1/2/3/4, rounded half up, at least 1."""
    return max(1, math.floor(common / DIVISOR[tier] + 0.5))


def cost(family):
    return COST[family]


def scrap(family, common):
    """(rounds, components): each full `rounds` of the round breaks down into `components`."""
    return {"Power": (common, 1), "Smart": (common, 2), "Tech": (2 * common, 1)}[family]


def recipe_price(common_price, tier, batch, batches):
    """Multiplier on Price.Ammo for a recipe item: `batches` crafted batches of the round."""
    return common_price * TIER_PRICE[tier] * batch * batches


def flat(text, key, name):
    m = re.search(rf'^AmmoOverhaul\.{key}\.{name}: (.*)$', text, flags=re.M)
    if not m:
        raise SystemExit(f"{key}: no {name} flat")
    return m.group(1).strip()


def strings(value):
    return [s.strip().strip('"') for s in value.strip("[]").split(",")]


def texts():
    """LocKey -> English text, from the hand-written and generated localization."""
    t = {}
    src = (SCRIPTS / "Localization.reds").read_text()
    for k, v in re.findall(r'this\.Text\("([^"]+)", "((?:[^"\\]|\\.)*)"\)', src):
        t[k] = v
    src = (SCRIPTS / "LocalizationRounds.reds").read_text()
    for k, v in re.findall(r'ArrayPush\(t, "([^"]+)"\); ArrayPush\(t, "((?:[^"\\]|\\.)*)"\);', src):
        t[k] = v
    return t


def display_names():
    """Ammo record -> its displayName LocKey, across every tweak file (following $base)."""
    names, bases = {}, {}
    for path in TWEAKS.glob("*.yaml"):
        text = path.read_text()
        for m in re.finditer(r'^(Ammo\.\w+):\n((?:[ \t]+.*\n|\n)*)', text, flags=re.M):
            body = m.group(2)
            n = re.search(r'^  displayName: LocKey#(\S+)', body, flags=re.M)
            b = re.search(r'^  \$base: (\S+)', body, flags=re.M)
            if n:
                names[m.group(1)] = n.group(1)
            if b:
                bases[m.group(1)] = b.group(1)

    def find(rec):
        while rec not in names and rec in bases:
            rec = bases[rec]
        return names.get(rec)
    return find


def settings():
    core = (TWEAKS / "core.yaml").read_text()
    return int(re.search(r'^AmmoOverhaul\.recipePriceBatches: (\d+)$', core, flags=re.M).group(1))


def caliber_block(key, text, loc, name_of, batches):
    family = flat(text, key, "family").strip('"')
    common = int(flat(text, key, "craftBatch"))
    ammos = strings(flat(text, key, "selectorAmmo"))
    tiers = [int(s) for s in strings(flat(text, key, "selectorTiers"))]
    y = [BEGIN, "", f"# {key}: {family}, {cost(family)} components a batch, {common} rounds a Common batch."]
    used = sorted(t for t in set(tiers) if t != LEGENDARY)
    for t in used:
        y.append(f"Crafting.AO_Cost_{family}_{t}:\n  $type: CraftingPackage\n  craftingRecipe:\n"
                 f"    - $type: RecipeElement\n      ingredient: {MATERIAL[t]}\n      amount: {cost(family)}\n")
    rounds, give = scrap(family, common)
    pairs, costs = [], []
    for ammo, t in zip(ammos, tiers):
        short = ammo.split(".", 1)[1]
        y.append(f"{ammo}.aoScrapRounds: {rounds}\n{ammo}.aoScrapGive: {give}")
        if ammo in VANILLA:
            y.append(f'{ammo}.aoRecipe: "{VANILLA[ammo]}"\n')
            continue
        if t == LEGENDARY:
            # Empty, so the base round's recipe isn't inherited through $base.
            y.append(f'{ammo}.aoRecipe: ""\n')
            continue
        batch = tier_batch(common, t)
        recipe = f"Items.AO_Recipe_{short}"
        key_name = name_of(ammo)
        if key_name is None or key_name not in loc:
            raise SystemExit(f"{ammo}: no display name")
        round_name = loc[key_name]
        price = recipe_price(COMMON_PRICE[key], t, batch, batches)
        costs.append(f"{ammo}:\n  CraftingData: Crafting.AO_Cost_{family}_{t}\n")
        y.append(f'{ammo}.aoRecipe: "{recipe}"')
        y.append(f"{recipe}:\n  $base: Items.AO_RecipeBase\n  quality: Quality.{QUALITY[t]}\n"
                 f"  displayName: LocKey#AO-Recipe-{short}\n  localizedDescription: LocKey#AO-Recipe-{short}-Desc\n"
                 f"  craftingResult:\n    $type: CraftingResult\n    item: {ammo}\n    amount: {batch}\n"
                 f"  tags: [Recipe, SkipActivityLogOnRemove, HideInBackpackUI, AO_Recipe, {QUALITY[t]}]\n"
                 f"  # {batches} batches of the round.\n"
                 f"  buyPrice:\n    - Price.Ammo\n    - Price.BuyPrice_StreetCred_Discount\n"
                 f"    - $type: ConstantStatModifier\n      statType: BaseStats.Price\n      modifierType: Multiplier\n      value: {price:g}\n"
                 f"  sellPrice:\n    - Price.Ammo\n"
                 f"    - $type: ConstantStatModifier\n      statType: BaseStats.Price\n      modifierType: Multiplier\n      value: {price:g}\n")
        pairs.append((f"AO-Recipe-{short}", f"{round_name}: load sheet"))
        pairs.append((f"AO-Recipe-{short}-Desc", f"Makes {batch} rounds of {round_name}."))
    return "\n".join(y) + "\n" + END + "\n", pairs, costs


def main():
    loc, name_of, batches = texts(), display_names(), settings()
    core = (TWEAKS / "core.yaml").read_text()
    pairs, costs = [], []
    for key in strings(re.search(r'^AmmoOverhaul\.calibers: \[(.*?)\]', core, flags=re.M | re.S).group(1).replace("\n", " ")):
        path = next(p for p in TWEAKS.glob("*.yaml") if f"AmmoOverhaul.{key}.family:" in p.read_text())
        text = path.read_text()
        block, mine, cost_updates = caliber_block(key, text, loc, name_of, batches)
        costs += [f"# {key}"] + cost_updates
        if BEGIN in text:
            text = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END) + "\n", lambda _: block, text, flags=re.S)
        else:
            text = text.rstrip("\n") + "\n\n" + block
        path.write_text(text)
        pairs += mine
    (TWEAKS / COSTS).write_text(
        "# Generated by tools/crafting/crafting.py (each round's crafting cost); edit there.\n"
        "# Updates of records the caliber files create. TweakXL can't type a one-line\n"
        "# 'Ammo.X.CraftingData: <record>' flat, so these are record updates, in a file named to load\n"
        "# after the caliber files.\n\n" + "\n".join(costs) + "\n")
    lines = [f'    ArrayPush(t, "{k}"); ArrayPush(t, "{v}");' for k, v in pairs]
    (SCRIPTS / "LocalizationRecipes.reds").write_text(
        "module AmmoOverhaul.Localization\n\n"
        "// Generated by tools/crafting/crafting.py (recipe items); edit there.\n"
        "public abstract class AORecipeTexts {\n"
        "  // Key, text, key, text, ...\n"
        "  public static func Pairs() -> array<String> {\n"
        "    let t: array<String>;\n" + "\n".join(lines) + "\n    return t;\n  }\n}\n")


if __name__ == "__main__":
    main()
